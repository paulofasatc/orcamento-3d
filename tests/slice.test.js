/**
 * Trechos reais dos comentários de PrusaSlicer, OrcaSlicer, Bambu Studio e Cura,
 * mais um 3MF mínimo com slice_info.config e plate_1.gcode.
 */
import { zipSync, strToU8 } from "../vendor/fflate.js";
import {
  gramsFromFilamentLength,
  parseDurationToSeconds,
  parseGcode,
  parseSliceBuffer,
  parseSliceInfoConfig,
  resolveSliceMass,
} from "../src/slice.js";

let passed = 0;
let failed = 0;

function assert(condition, message, detail = "") {
  if (condition) {
    passed += 1;
    console.log(`  ok  ${message}`);
  } else {
    failed += 1;
    console.error(`  FAIL  ${message}${detail ? `\n        ${detail}` : ""}`);
  }
}

function almostEqual(a, b, eps = 1e-4) {
  return Math.abs(a - b) <= eps;
}

console.log("Orça3D — fatiadores\n");

console.log("Duração");
assert(parseDurationToSeconds("1h 2m 3s") === 3723, "1h 2m 3s");
assert(parseDurationToSeconds("2d 1h 0m 1s") === 2 * 86400 + 3600 + 1, "dias + horas + segundos");
assert(parseDurationToSeconds("0h 12m 30s") === 750, "formato Bambu com zero hora");
assert(parseDurationToSeconds("15m 30s") === 930, "minutos e segundos");
assert(parseDurationToSeconds("45s") === 45, "só segundos");

console.log("\nPrusaSlicer");
const prusa = parseGcode(`; generated by PrusaSlicer 2.7.4+linux64 on 2024-05-01 at 10:00:00 UTC
; filament_density = 1.24
; filament used [mm] = 1000.00
; filament used [cm3] = 2.41
; filament used [g] = 2.98
; estimated printing time (normal mode) = 1h 2m 3s
; estimated printing time (silent mode) = 2h 0m 0s
; estimated first layer printing time (normal mode) = 30s
`);
assert(prusa.slicer.id === "prusa", `fatiador PrusaSlicer (foi ${prusa.slicer.name})`);
assert(prusa.slicer.version === "2.7.4+linux64", `versão ${prusa.slicer.version}`);
assert(almostEqual(prusa.massGrams, 2.98), "usa as gramas, não o volume", `obtido ${prusa.massGrams}`);
assert(prusa.massSource === "grams", "origem gramas");
assert(prusa.printTimeSeconds === 3723, "tempo do modo normal, não o silencioso nem a primeira camada", `obtido ${prusa.printTimeSeconds}`);

console.log("\nOrcaSlicer");
const orca = parseGcode(`; generated by OrcaSlicer 2.2.0 on 2025-01-01 at 00:00:00 UTC
; filament used [mm] = 500, 250
; filament used [g] = 1.20, 0.50
; total filament used [g] = 1.70
; estimated printing time (normal mode) = 15m 30s
`);
assert(orca.slicer.id === "orca" && orca.slicer.version === "2.2.0", "OrcaSlicer 2.2.0");
assert(almostEqual(orca.massGrams, 1.7), "prefere o total em gramas e não soma de novo", `obtido ${orca.massGrams}`);
assert(orca.printTimeSeconds === 930, "15m 30s");

console.log("\nBambu Studio");
const bambu = parseGcode(`; HEADER_BLOCK_START
; BambuStudio 01.09.01.66
; model printing time: 0h 10m 0s; total estimated time: 0h 12m 30s
; total layer number: 50
; total filament length [mm] : 2000.00
; total filament volume [cm^3] : 4.81
; total filament weight [g] : 5.96
; filament_density: 1.24
; filament_diameter: 1.75
; HEADER_BLOCK_END
`);
assert(bambu.slicer.id === "bambu", `Bambu Studio (foi ${bambu.slicer.id})`);
assert(bambu.slicer.version === "01.09.01.66", `versão ${bambu.slicer.version}`);
assert(almostEqual(bambu.massGrams, 5.96), "peso do cabeçalho", `obtido ${bambu.massGrams}`);
assert(bambu.printTimeSeconds === 750, "total estimated time, não o model printing time", `obtido ${bambu.printTimeSeconds}`);

console.log("\nCura — comprimento em metros");
const cura = parseGcode(
  `;FLAVOR:Marlin
;TIME:3661
;Filament used: 1.5m
;Layer height: 0.2
;Generated with Cura_SteamEngine 5.6.0
`,
  { densityGCm3: 1.24, diameterMm: 1.75 }
);
assert(cura.slicer.id === "cura" && cura.slicer.version === "5.6.0", "Cura 5.6.0");
assert(cura.printTimeSeconds === 3661, ";TIME: em segundos");
const expectedCuraGrams = gramsFromFilamentLength(1500, 1.75, 1.24);
assert(cura.massSource === "length", "massa convertida do comprimento");
assert(almostEqual(cura.massGrams, expectedCuraGrams, 1e-6), "1,5 m × 1,75 mm × 1,24 g/cm³", `obtido ${cura.massGrams}`);
assert(almostEqual(cura.filamentLengthMm, 1500), "comprimento 1500 mm");

const curaMulti = parseGcode(
  `;TIME:100
;Filament used: 1m, 0.5m
;Generated with Cura_SteamEngine 5.4.0
`,
  { densityGCm3: 1.24, diameterMm: 1.75 }
);
assert(almostEqual(curaMulti.filamentLengthMm, 1500), "Cura soma os comprimentos dos extrusores");
assert(
  almostEqual(curaMulti.massGrams, gramsFromFilamentLength(1500, 1.75, 1.24), 1e-6),
  "massa dos dois comprimentos"
);

console.log("\nComprimento com densidade do arquivo e troca de densidade");
const lengthOnly = parseGcode(`; generated by PrusaSlicer 2.6.0+linux64
; filament used [mm] = 1000
; filament_diameter = 1.75
; filament_density = 1.24
; estimated printing time (normal mode) = 10m
`);
const fromFile = gramsFromFilamentLength(1000, 1.75, 1.24);
assert(lengthOnly.massSource === "length", "sem gramas, converte o comprimento");
assert(almostEqual(lengthOnly.massGrams, fromFile, 1e-6), "densidade e diâmetro do arquivo");
assert(lengthOnly.printTimeSeconds === 600, "10m");
const heavier = resolveSliceMass(
  { ...lengthOnly, densityGCm3: null, massGrams: null },
  { densityGCm3: 1.27, diameterMm: 1.75 }
);
assert(
  almostEqual(heavier.massGrams, gramsFromFilamentLength(1000, 1.75, 1.27), 1e-6),
  "sem densidade no arquivo, usa a do perfil"
);

const noDensity = parseGcode(`; generated by PrusaSlicer 2.6.0
; filament used [mm] = 1000
; estimated printing time (normal mode) = 1m
`);
assert(noDensity.massGrams == null, "sem densidade não inventa gramas");
assert(noDensity.warnings.some((w) => /densidade/i.test(w)), "aviso pede a densidade");

console.log("\nSuperSlicer e arquivo sem números");
const superSlicer = parseGcode(`; generated by SuperSlicer 2.5.59 on 2024-01-01
; filament used [g] = 8
; estimated printing time (normal mode) = 1h 0m 0s
`);
assert(superSlicer.slicer.id === "superslicer", "SuperSlicer não cai em PrusaSlicer");
assert(superSlicer.printTimeSeconds === 3600 && superSlicer.massGrams === 8, "peso e tempo do SuperSlicer");

const empty = parseGcode("; no useful comments\nG1 X0 Y0\n");
assert(empty.slicer.id === "unknown", "fatiador desconhecido");
assert(empty.massGrams == null && empty.printTimeSeconds == null, "sem peso e sem tempo");
assert(empty.warnings.some((w) => /Não encontrei/i.test(w)), "aviso amigável");

console.log("\nslice_info.config");
const xml = `<?xml version="1.0" encoding="UTF-8"?>
<config>
  <header>
    <header_item key="X-BBL-Client-Type" value="slicer"/>
    <header_item key="X-BBL-Client-Version" value="01.10.00.89"/>
  </header>
  <plate>
    <metadata key="index" value="1"/>
    <metadata key="prediction" value="100"/>
    <metadata key="weight" value="2.5"/>
    <filament id="1" type="PLA" color="#FFFFFF" used_m="1.0" used_g="2.0"/>
    <filament id="2" type="PLA" color="#000000" used_m="0.2" used_g="0.5"/>
  </plate>
  <plate>
    <metadata key="index" value="2"/>
    <metadata key="prediction" value="50"/>
    <metadata key="weight" value="1.25"/>
  </plate>
</config>`;
const info = parseSliceInfoConfig(xml);
assert(info.plateCount === 2, "duas placas");
assert(info.printTimeSeconds === 150, "soma o prediction das placas", `obtido ${info.printTimeSeconds}`);
assert(almostEqual(info.massFromFileGrams, 3.75), "soma o weight e não soma used_g de novo", `obtido ${info.massFromFileGrams}`);
assert(info.slicer.version === "01.10.00.89", "versão do cliente no XML");

const zeroWeight = parseSliceInfoConfig(`<config><plate>
  <metadata key="prediction" value="10"/>
  <metadata key="weight" value="0"/>
  <filament id="1" used_m="1" used_g="4.5"/>
</plate></config>`);
assert(almostEqual(zeroWeight.massFromFileGrams, 4.5), "se o weight é 0, usa a soma de used_g");

console.log("\n3MF fatiado");
const plate = `; generated by OrcaSlicer 2.1.1
; filament used [g] = 9.99
; estimated printing time (normal mode) = 3h 0m 0s
`;
const archive = zipSync({
  "Metadata/slice_info.config": strToU8(xml),
  "Metadata/plate_1.gcode": strToU8(plate),
  "3D/3dmodel.model": strToU8("<model/>"),
});
const sliced = parseSliceBuffer(archive, "peca.gcode.3mf");
assert(sliced.format === "3mf", "formato 3mf");
assert(sliced.slicer.id === "orca" && sliced.slicer.version === "2.1.1", "o G-code da placa identifica o OrcaSlicer");
assert(almostEqual(sliced.massGrams, 3.75), "peso vem do slice_info, não do G-code embutido", `obtido ${sliced.massGrams}`);
assert(sliced.printTimeSeconds === 150, "tempo vem do slice_info");

const gcodeOnly = zipSync({
  "Metadata/plate_1.gcode": strToU8(plate),
});
const fromPlate = parseSliceBuffer(gcodeOnly, "placa.3mf");
assert(fromPlate.slicer.id === "orca", "sem slice_info, lê plate_*.gcode");
assert(almostEqual(fromPlate.massGrams, 9.99) && fromPlate.printTimeSeconds === 10800, "peso e tempo do G-code da placa");

let threw = false;
let message = "";
try {
  parseSliceBuffer(new TextEncoder().encode("not a zip"), "modelo.3mf");
} catch (err) {
  threw = true;
  message = err.message;
}
assert(threw && /ZIP válido/i.test(message), "3MF inválido explica o problema em português", message);

let threwProject = false;
try {
  parseSliceBuffer(zipSync({ "3D/3dmodel.model": strToU8("<model/>") }), "projeto.3mf");
} catch (err) {
  threwProject = /fatiamento/i.test(err.message);
}
assert(threwProject, "3MF de projeto, sem fatiar, pede um .gcode.3mf");

const asGcode = parseSliceBuffer(new TextEncoder().encode(plate), "placa.gcode");
assert(asGcode.slicer.id === "orca" && almostEqual(asGcode.massGrams, 9.99), "parseSliceBuffer lê .gcode");

console.log(`\n${passed} ok, ${failed} falha(s)`);
if (failed > 0) process.exit(1);
